# STEP 1: Show the Sudoku board using Python (Flask). No JavaScript.
from flask import Flask, render_template

app = Flask(__name__)

# 0 = empty cell
PUZZLE = [
    [5, 3, 0, 0, 7, 0, 0, 0, 0],
    [6, 0, 0, 1, 9, 5, 0, 0, 0],
    [0, 9, 8, 0, 0, 0, 0, 6, 0],
    [8, 0, 0, 0, 6, 0, 0, 0, 3],
    [4, 0, 0, 8, 0, 3, 0, 0, 1],
    [7, 0, 0, 0, 2, 0, 0, 0, 6],
    [0, 6, 0, 0, 0, 0, 2, 8, 0],
    [0, 0, 0, 4, 1, 9, 0, 0, 5],
    [0, 0, 0, 0, 8, 0, 0, 7, 9],
]


@app.route("/")
def home():
    # Python sends the board to the HTML template
    return render_template("index.html", board=PUZZLE, given=PUZZLE, message="")


if __name__ == "__main__":
    app.run(debug=True)